"""Write the deployable ECS app template: deploy/ecs/app.yaml plus the read-only policy
from iam/aws-audit-role.yaml (its one source), as text. Usage: --help."""

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP_SOURCE = os.path.join(ROOT, "deploy", "ecs", "app.yaml")
ROLE_SOURCE = os.path.join(ROOT, "iam", "aws-audit-role.yaml")
DEFAULT_OUTPUT = os.path.join(ROOT, "build", "ecs", "aws-cleanup-app.yaml")

MARKER = "# GENERATED: the read-only policy from iam/aws-audit-role.yaml"
POLICY_START = "- PolicyName: aws-resource-audit-read-only"
HEADER = ("# GENERATED by tools/build_ecs_template.py from deploy/ecs/app.yaml and\n"
          "# iam/aws-audit-role.yaml - do not edit; edit those and regenerate.\n")


class TemplateError(Exception):
    """A source file no longer has the shape this generator relies on."""


def _indent(line):
    return len(line) - len(line.lstrip(" "))


def read_policy(role_text):
    """(indent, lines) of the role's read-only policy item, comments included."""
    lines = role_text.splitlines()
    starts = [i for i, line in enumerate(lines) if line.strip() == POLICY_START]
    if len(starts) != 1:
        raise TemplateError(f"expected one '{POLICY_START}' in iam/aws-audit-role.yaml")
    start = starts[0]
    indent = _indent(lines[start])
    end = start + 1
    while end < len(lines) and (not lines[end].strip() or _indent(lines[end]) > indent):
        end += 1
    block = lines[start:end]
    while block and not block[-1].strip():
        block.pop()
    return indent, block


def _shift(line, by):
    if not line.strip():
        return ""
    if by >= 0:
        return " " * by + line
    if _indent(line) < -by:
        raise TemplateError("the marker is indented less than the policy can be moved")
    return line[-by:]


def insert_policy(app_text, role_text):
    """app_text with its one marker line replaced by the role's policy, re-indented."""
    indent, block = read_policy(role_text)
    out, found = [], 0
    for line in app_text.splitlines():
        if line.strip() == MARKER:
            found += 1
            out.extend(_shift(policy_line, _indent(line) - indent) for policy_line in block)
        else:
            out.append(line)
    if found != 1:
        raise TemplateError(f"expected one '{MARKER}' line in deploy/ecs/app.yaml, found {found}")
    return "\n".join(out) + "\n"


def set_default(text, parameter, value):
    """Add `Default: value` under a String parameter that has none."""
    pattern = re.compile(rf"^(  {parameter}:\n    Type: String\n)", re.M)
    new_text, count = pattern.subn(lambda m: m.group(1) + f"    Default: '{value}'\n", text)
    if count != 1:
        raise TemplateError(f"parameter {parameter} not found as '  {parameter}:' + 'Type: String'")
    return new_text


def build(app_text, role_text, backend_image=None, frontend_image=None):
    """The deployable template's text."""
    if (backend_image is None) != (frontend_image is None):
        raise TemplateError("give both images or neither")
    text = insert_policy(app_text, role_text)
    if backend_image:
        text = set_default(text, "BackendImage", backend_image)
        text = set_default(text, "FrontendImage", frontend_image)
    return HEADER + text


def _read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default=DEFAULT_OUTPUT, help="where to write the template")
    parser.add_argument("--backend-image", help="make this BackendImage's default (the release workflow does)")
    parser.add_argument("--frontend-image", help="make this FrontendImage's default; give both images or neither")
    args = parser.parse_args(argv)
    try:
        text = build(_read(APP_SOURCE), _read(ROLE_SOURCE), args.backend_image, args.frontend_image)
    except TemplateError as e:
        sys.exit(f"build_ecs_template: {e}")
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(text)
    print(args.output)


if __name__ == "__main__":
    main()
